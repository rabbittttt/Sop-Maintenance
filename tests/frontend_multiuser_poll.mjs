import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const source=readFileSync(new URL('../web/app.js',import.meta.url),'utf8');
const dialog={open:false},document={hidden:false,querySelector:()=>dialog,querySelectorAll:()=>[]};
const context=vm.createContext({document,localStorage:{getItem:()=>null},polls:0,loads:0,
  status:{status:'frontend',message:'',data_revision:'2:1:1',source_refresh:{}}});
vm.runInContext(source.split("document.addEventListener('click'")[0],context);
const run=code=>vm.runInContext(code,context);
run(`state={workbook_sync:{status:'frontend',message:'',data_revision:'1:1:1'},source_refresh:{}};
  api=async()=>{polls++;return status;};
  load=async()=>{loads++;state.workbook_sync={...status};};
  generationStatusChanged=()=>false;`);
assert.equal(run('workbookStrip()'),'');
await run('pollWorkbookStatus()');
assert.equal(context.loads,1,'Another user saving refreshes an idle page.');
await run('pollWorkbookStatus()');
assert.equal(context.loads,1,'An unchanged revision does not reload.');
document.hidden=true;
const backgroundPolls=context.polls;
await run('pollWorkbookStatus()');
assert.equal(context.polls,backgroundPolls,'A background tab does not poll the service.');
document.hidden=false;
run("gridDraft={marker:'unsaved'};status.data_revision='3:1:1';");
const polls=context.polls;
await run('pollWorkbookStatus()');
assert.equal(context.polls,polls);
assert.equal(run('gridDraft.marker'),'unsaved');
run('gridDraft=null;');
dialog.open=true;
await run('pollWorkbookStatus()');
assert.equal(context.loads,1,'An open import dialog is not disturbed.');
dialog.open=false;
await run('pollWorkbookStatus()');
assert.equal(context.loads,2);
let finish;
context.delay=new Promise(resolve=>{finish=resolve;});
run('api=()=>delay;');
const pending=run('pollWorkbookStatus()');
run("gridDraft={marker:'started-during-poll'};");
finish({status:'frontend',data_revision:'4:1:1'});
await pending;
assert.equal(context.loads,2,'Starting to edit while a status request is in flight also protects the draft.');
console.log('PASS: multiuser status refresh, unchanged revisions, protected drafts and import dialogs.');
